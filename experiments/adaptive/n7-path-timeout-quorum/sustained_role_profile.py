class SustainedRoleProfileError(ValueError):
    """The scheduled one-actor profile is not bounded exactly."""


def canonical_transition_request() -> str:
    """Return the exact transition request bytes accepted by the base builder."""
    return json.dumps(
        CONSENSUS_PROFILE["transition"], sort_keys=True, separators=(",", ":")
    )


def validate_common_manager_argv(command: Sequence[str]) -> None:
    """Require the public run/source/output/tree bindings shared by both arms."""
    argv = tuple(command)
    if not argv or any(type(value) is not str or not value for value in argv):
        raise SustainedRoleProfileError("manager argv is not a nonempty string sequence")
    for option in (
        "--structured-event-run-id", "--structured-event-source-instance",
        "--structured-event-output", "--epoch-zero-tree-file",
    ):
        if argv.count(option) != 1:
            raise SustainedRoleProfileError(f"manager argv must contain exactly one {option}")
        position = argv.index(option)
        if position + 1 >= len(argv) or not argv[position + 1]:
            raise SustainedRoleProfileError(f"manager argv has no value for {option}")


def validate_adaptive_manager_argv(command: Sequence[str]) -> None:
    """Reject a manager argv that cannot be replayed from the frozen profile.

    This validates public/path bindings only.  It intentionally does not
    pretend that a private key path proves the issuer's public key or that an
    argv proves process lifecycle; those remain in the explicit no-go list.
    """
    argv = tuple(command)
    validate_common_manager_argv(argv)
    required = MATERIALIZATION_MAP["adaptive_e1_manager_argv"]["required_options"]
    for option in required:
        if argv.count(option) != 1:
            raise SustainedRoleProfileError(f"adaptive manager argv must contain exactly one {option}")
        position = argv.index(option)
        if position + 1 >= len(argv) or not argv[position + 1]:
            raise SustainedRoleProfileError(f"adaptive manager argv has no value for {option}")
    if argv[argv.index("--issuer-id") + 1] != str(ACTOR_ID):
        raise SustainedRoleProfileError("adaptive manager issuer differs from the frozen issuer id")
    if argv[argv.index("--activation-delay-blocks") + 1] != str(CONSENSUS_PROFILE["activation_delay_blocks"]):
        raise SustainedRoleProfileError("adaptive manager activation delay differs from the frozen profile")
    if argv[argv.index("--transition-request") + 1] != canonical_transition_request():
        raise SustainedRoleProfileError("adaptive manager transition request differs from the frozen profile")


def validate_path_timeout_manager_selection(command: Sequence[str]) -> None:
    """Require the inherited v4 path-selection argv without static fault flags."""
    argv = tuple(command)
    if argv.count("--required-nonresponsive") != 1 or (
        argv[argv.index("--required-nonresponsive") + 1] !=
        MATERIALIZATION_MAP["path_timeout_manager_selection"]["required_nonresponsive"]
    ):
        raise SustainedRoleProfileError("manager required-nonresponsive differs from frozen selection policy")
    endpoints = [argv[index + 1] for index, value in enumerate(argv[:-1]) if value == "--replica"]
    if len(endpoints) != MATERIALIZATION_MAP["path_timeout_manager_selection"]["replica_endpoint_count"]:
        raise SustainedRoleProfileError("manager must bind exactly seven replica endpoints")
    if any(not endpoint.startswith(f"{replica},") for replica, endpoint in enumerate(endpoints)):
        raise SustainedRoleProfileError("manager replica endpoints do not bind replica identities in order")
    selection = MATERIALIZATION_MAP["path_timeout_manager_selection"]
    for option, expected in selection["exact_options"].items():
        if argv.count(option) != 1 or argv[argv.index(option) + 1] != expected:
            raise SustainedRoleProfileError(f"manager {option} differs from frozen selection policy")
    for option in selection["dynamic_options"]:
        if argv.count(option) != 1 or not argv[argv.index(option) + 1]:
            raise SustainedRoleProfileError(f"manager {option} lacks a bound value")
    if argv[argv.index("--fault-window-arm-run-id") + 1] != argv[argv.index("--structured-event-run-id") + 1]:
        raise SustainedRoleProfileError("manager fault-window arm run id differs from structured run id")


def validate_fixed_e0_manager_argv(command: Sequence[str]) -> None:
    """Reject adaptive successor options in the fixed-E0 arm.

    The current trusted base materializer cannot produce the required explicit
    no-successor terminal.  This function therefore only records the negative
    boundary; a future launcher must add and independently replay that native
    manager mode before this arm becomes executable.
    """
    argv = tuple(command)
    validate_common_manager_argv(argv)
    for option in MATERIALIZATION_MAP["fixed_e0_manager_argv"]["forbidden_options"]:
        if option in argv:
            raise SustainedRoleProfileError(f"fixed-E0 manager argv must not contain {option}")


def _positive_uint64(value: object, label: str) -> int:
    if type(value) is not int or value <= 0 or value > (1 << 64) - 1:
        raise SustainedRoleProfileError(f"{label} is not a positive uint64")
    return value


def argv_overlay(*, window_start_monotonic_ns: int,
                 window_end_monotonic_ns: int) -> tuple[str, ...]:
    """Return the exact native scheduled-fault options for actor 1.

    The mode is deliberately configuration-independent: Epoch-1 leaf
    placement must not turn the fault off merely by changing epoch identity.
    A later runner must obtain both timestamps from the same raw-clock domain
    that it preserves in the evidence bundle.
    """
    start = _positive_uint64(window_start_monotonic_ns, "fault window start")
    end = _positive_uint64(window_end_monotonic_ns, "fault window end")
    minimum_duration = COMMON_HORIZON_NS + MINIMUM_POST_START_ANCHOR_SLACK_NS
    if end <= start or end - start < minimum_duration:
        raise SustainedRoleProfileError(
            "fault window must cover a positive post-start anchor allowance plus the 60-second common horizon"
        )
    return (
        "--experiment-byzantine-mode", NATIVE_MODE,
        "--experiment-byzantine-window", PROFILE_ID,
        "--experiment-rotating-omission-actors", str(ACTOR_ID),
        "--experiment-byzantine-window-start-monotonic-ns", str(start),
        "--experiment-byzantine-window-end-monotonic-ns", str(end),
        "--experiment-byzantine-max-omissions-per-proposal",
        str(MAX_OMISSIONS_PER_PROPOSAL),
        "--experiment-rotating-omission-context-limit", str(CONTEXT_LIMIT),
    )


